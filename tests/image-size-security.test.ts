test("the patched image-size package rejects known zero-progress loops", async () => {
  const packageJson = JSON.parse(
    await readFile("node_modules/image-size/package.json", "utf8"),
  ) as { version?: string };
  assert.equal(packageJson.version, "2.0.3-saige.2");

  for (const [format, bytes] of Object.entries(maliciousInputs)) {
    const source = `
      import { imageSize } from "image-size";
      const bytes = new Uint8Array(${JSON.stringify(bytes)});
      let rejected = false;
      try { imageSize(bytes); } catch { rejected = true; }
      if (!rejected) process.exit(2);
    `;
    const result = spawnSync(
      process.execPath,
      ["--input-type=module", "--eval", source],
      {
        cwd: process.cwd(),
        encoding: "utf8",
        timeout: 2_000,
        windowsHide: true,
      },
    );
    assert.notEqual(
      (result.error as NodeJS.ErrnoException | undefined)?.code,
      "ETIMEDOUT",
      `${format} parser failed to make progress`,
    );
    assert.equal(
      result.status,
      0,
      `${format} payload was not rejected: ${result.stderr}`,
    );
  }
});
